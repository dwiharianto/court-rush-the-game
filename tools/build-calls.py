"""Renders the umpire and line judge calls ('Out!', 'Fault!', 'Let!', 'Correction!')
into src/assets/calls.js, so the game plays them as audio clips instead of relying on
the browser's speech voices (which are often missing or silent in embedded pages).

Voice: Piper neural TTS with the en-us-libritts-high model (trained on LibriTTS,
CC BY 4.0, https://www.openslr.org/60/). Setup:
  python3 -m venv venv && ./venv/bin/pip install piper-tts
  curl -LO https://github.com/rhasspy/piper/releases/download/v0.0.2/voice-en-us-libritts-high.tar.gz
  tar -xzf voice-en-us-libritts-high.tar.gz
  ./venv/bin/python tools/build-calls.py path/to/en-us-libritts-high.onnx
"""
import base64, json, sys
from pathlib import Path
import numpy as np
from piper import PiperVoice, SynthesisConfig

MODEL = sys.argv[1]
OUT_SR = 16000
# speakers picked by measured pitch: two lower line judge voices and a higher one
LINE_JUDGES = [132, 139, 40]
UMPIRE = 139
CALLS = {
    'out': [('Out!', LINE_JUDGES)],
    'fault': [('Fault!', LINE_JUDGES)],
    'let': [('Let!', [UMPIRE])],
    'correction': [('Correction!', [UMPIRE])],
}
TAKES = [dict(length_scale=0.86, noise_scale=0.55, noise_w_scale=0.5), dict(length_scale=0.95, noise_scale=0.4, noise_w_scale=0.7)]

voice = PiperVoice.load(MODEL)
SR = voice.config.sample_rate


def resample(a, sr_in, sr_out):
    n = int(round(len(a) * sr_out / sr_in))
    spec = np.fft.rfft(a)
    keep = n // 2 + 1
    spec = spec[:keep] if keep <= len(spec) else np.pad(spec, (0, keep - len(spec)))
    return np.fft.irfft(spec, n) * (n / len(a))


def clean(a):
    # trim the silence, short fades, normalise just below full scale
    env = np.abs(a)
    on = np.where(env > 0.02 * env.max())[0]
    a = a[max(0, on[0] - 160):min(len(a), on[-1] + 800)]
    f = 80
    a[:f] *= np.linspace(0, 1, f)
    a[-f * 4:] *= np.linspace(1, 0, f * 4)
    return a / (np.abs(a).max() + 1e-9) * 0.89


clips = {}
for name, lines in CALLS.items():
    clips[name] = []
    for text, speakers in lines:
        for sid in speakers:
            for take in (TAKES if len(speakers) > 1 else TAKES[:1]):
                cfg = SynthesisConfig(speaker_id=sid, **take)
                a = np.concatenate([c.audio_float_array for c in voice.synthesize(text, syn_config=cfg)]).astype(np.float64)
                a = clean(resample(a, SR, OUT_SR))
                pcm = np.clip(np.round(a * 32767), -32768, 32767).astype('<i2').tobytes()
                clips[name].append(base64.b64encode(pcm).decode())
                print(f'{name:10s} speaker {sid:3d}  {len(a) / OUT_SR:.2f} s')

head = ('// Generated by tools/build-calls.py: umpire and line judge calls, 16-bit PCM, base64.\n'
        '// Voice: Piper TTS, en-us-libritts-high model (trained on LibriTTS, CC BY 4.0).\n')
out = Path(__file__).resolve().parent.parent / 'src' / 'assets' / 'calls.js'
out.write_text(head + 'export default ' + json.dumps({'sampleRate': OUT_SR, 'clips': clips}) + ';\n')
print('wrote', out, out.stat().st_size // 1024, 'KB')
